  const sync = () => {
    const edited = Object.hasOwn((state.variants[state.template] ?? {})[key] ?? {}, i);
    help.textContent = edited ? `as attested: ${String(named).toLowerCase()}` : '';
    help.hidden = !help.textContent;
    reset.hidden = !edited;
  };
  sync();
