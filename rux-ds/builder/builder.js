function setWidth(w) {
  state.width = w;
  for (const b of document.querySelectorAll('[data-width]')) b.setAttribute('aria-pressed', String(b.dataset.width === w));
  if (w === 'fit') {
    frame.style.inlineSize = '100%';
    wrap.style.transform = '';
    wrap.style.blockSize = '';
    wrap.style.inlineSize = '';
  } else {
    const px = Number(w);
    const pane = wrap.parentElement.clientWidth;
    const scale = Math.min(1, pane / px);
    frame.style.inlineSize = `${px}px`;
    wrap.style.inlineSize = `${px}px`;
    wrap.style.transform = scale < 1 ? `scale(${scale})` : '';
    wrap.style.blockSize = scale < 1 ? `${frame.getBoundingClientRect().height * scale}px` : '';
  }
  render();
}

