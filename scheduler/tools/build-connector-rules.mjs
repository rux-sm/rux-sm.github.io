#!/usr/bin/env node
//
// Joins the Scheduler's rule files into scheduler/connector/rules.ts, so the
// Claude app's connector answers with the pages' own rules: a draft's fields
// as draft-fields.js checks them, and a trip's gaps as Prep and the To do
// list read them. Each file runs as the page runs it, against a `window` of
// its own, and the connector imports that window. `npm run build` writes it;
// `--check` says whether the committed copy is the files as they are now.
//
//   node scheduler/tools/build-connector-rules.mjs [--check]
//
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCHEDULER = resolve(fileURLToPath(import.meta.url), '..', '..');
const OUT = join(SCHEDULER, 'connector', 'rules.ts');

// In the order index.html loads them, each after the files it reads.
export const FILES = [
  'requirements.js', 'leg-facts.js', 'billing.js', 'follow-up.js', 'checklist.js', 'week.js',
  'share/driver-words.js', 'driver-job.js', 'clashes.js', 'to-do.js', 'departures.js', 'draft-fields.js',
];

export function build() {
  const parts = FILES.map(f => `// ── ${f}\n${readFileSync(join(SCHEDULER, f), 'utf8').trimEnd()}\n`);
  return [
    '// @ts-nocheck',
    '// Generated by scheduler/tools/build-connector-rules.mjs from the Scheduler\'s rule',
    '// files, which the pages load; `npm run build` writes it again. Never edited by hand.',
    'const window = {};',
    '',
    ...parts,
    'export default window;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = build();
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(OUT, 'utf8'); } catch { /* missing reads as stale */ }
    if (now !== text) {
      console.log('  FAIL  connector rules  scheduler/connector/rules.ts is not the rule files as they are; run npm run build');
      process.exit(1);
    }
    console.log(`   ok   connector rules  rules.ts is ${FILES.length} rule files as they are`);
  } else {
    writeFileSync(OUT, text);
    console.log(`  wrote scheduler/connector/rules.ts from ${FILES.length} rule files`);
  }
}
