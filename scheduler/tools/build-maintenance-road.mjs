#!/usr/bin/env node
//
// Writes the two files scheduler/maintenance-status/ borrows, so the
// maintenance link's status says what the board says about a bus:
//   road.ts     the board's road files joined, a leg's times by week.js and
//               its stops and where the bus is on them by road.js, each run
//               as the board runs it against a `window` of its own, which the
//               function imports;
//   samsara.ts  samsara-now's handler.ts as it is, so a bus's readings and
//               its path are read one way.
// `npm run build` writes them; `--check` says whether the committed copies
// are the files as they are now.
//
//   node scheduler/tools/build-maintenance-road.mjs [--check]
//
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCHEDULER = resolve(fileURLToPath(import.meta.url), '..', '..');
const DIR = join(SCHEDULER, 'maintenance-status');

// In the order index.html loads them, each after the files it reads.
export const FILES = ['trip-shape.js', 'week.js', 'road.js'];
const HEAD = from => `// Generated by scheduler/tools/build-maintenance-road.mjs from ${from};\n`
  + '// `npm run build` writes it again. Never edited by hand.';

export function build() {
  const parts = FILES.map(f => `// ── ${f}\n${readFileSync(join(SCHEDULER, f), 'utf8').trimEnd()}\n`);
  return {
    'road.ts': ['// @ts-nocheck', HEAD("the board's road files"), 'const window = {};', '', ...parts, 'export default window;', ''].join('\n'),
    'samsara.ts': `${HEAD('scheduler/samsara-now/handler.ts')}\n\n${readFileSync(join(SCHEDULER, 'samsara-now', 'handler.ts'), 'utf8')}`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = build();
  if (process.argv.includes('--check')) {
    const stale = Object.keys(out).filter(name => {
      try { return readFileSync(join(DIR, name), 'utf8') !== out[name]; } catch { return true; }
    });
    if (stale.length) {
      console.log(`  FAIL  maintenance road  ${stale.map(n => `scheduler/maintenance-status/${n}`).join(', ')} not as the files are; run npm run build`);
      process.exit(1);
    }
    console.log(`   ok   maintenance road  road.ts is ${FILES.length} road files and samsara.ts samsara-now's handler, as they are`);
  } else {
    for (const [name, text] of Object.entries(out)) writeFileSync(join(DIR, name), text);
    console.log(`  wrote scheduler/maintenance-status/road.ts and samsara.ts`);
  }
}
