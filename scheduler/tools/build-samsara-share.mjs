#!/usr/bin/env node
//
// Writes the file scheduler/samsara-share/ borrows, so a customer's tracking
// link opens with a leg's yard-out and closes after its yard-back as
// samsara-miles reads them:
//   miles.ts  samsara-miles's handler.ts as it is, for a trip's legs and a
//             leg's window.
// `npm run build` writes it; `--check` says whether the committed copy is the
// file as it is now.
//
//   node scheduler/tools/build-samsara-share.mjs [--check]
//
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCHEDULER = resolve(fileURLToPath(import.meta.url), '..', '..');
const DIR = join(SCHEDULER, 'samsara-share');
const FROM = 'scheduler/samsara-miles/handler.ts';

export function build() {
  return {
    'miles.ts': `// Generated by scheduler/tools/build-samsara-share.mjs from ${FROM};\n`
      + '// `npm run build` writes it again. Never edited by hand.\n\n'
      + readFileSync(join(SCHEDULER, 'samsara-miles', 'handler.ts'), 'utf8'),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = build();
  if (process.argv.includes('--check')) {
    const stale = Object.keys(out).filter(name => {
      try { return readFileSync(join(DIR, name), 'utf8') !== out[name]; } catch { return true; }
    });
    if (stale.length) {
      console.log(`  FAIL  samsara share  ${stale.map(n => `scheduler/samsara-share/${n}`).join(', ')} not as the file is; run npm run build`);
      process.exit(1);
    }
    console.log("   ok   samsara share  miles.ts is samsara-miles's handler, as it is");
  } else {
    for (const [name, text] of Object.entries(out)) writeFileSync(join(DIR, name), text);
    console.log('  wrote scheduler/samsara-share/miles.ts');
  }
}
